    IDX_BZTP_LCLS_CD    VARCHAR(3),
    IDX_BZTP_MCLS_CD    VARCHAR(3),
    IDX_BZTP_SCLS_CD    VARCHAR(3),
    IDX_BZTP_LCLS_NM    VARCHAR(60),
    IDX_BZTP_MCLS_NM    VARCHAR(60),
    IDX_BZTP_SCLS_NM    VARCHAR(60),
    STD_IDST_CLSF_CD    VARCHAR(6),
    STD_IDST_CLSF_NM    VARCHAR(130),
    FRNR_PSNL_LMT_RT    VARCHAR(24),
    TR_STOP_YN          VARCHAR(1),
    ADMN_ITEM_YN        VARCHAR(1),
    LSTG_ABOL_DT        VARCHAR(8),
    SCTS_MKET_LSTG_DT   VARCHAR(8),
