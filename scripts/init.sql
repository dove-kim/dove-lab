-- 상장주식수 변경이력(KRX 권위값). 값이 바뀐 날만 한 행 → as-of(EFFECTIVE_DATE≤거래일 중 최신) 조회로 그 시점 주식수. 시총 계산의 PIT 입력.
CREATE TABLE IF NOT EXISTS STOCK_SHARE_COUNT (
