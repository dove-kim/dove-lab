    INDEX IDX_SD_BZTP_MCLS (IDX_BZTP_MCLS_NM),
    INDEX IDX_SD_BZTP_SCLS (IDX_BZTP_SCLS_NM),
    INDEX IDX_SD_STD_IDST (STD_IDST_CLSF_NM),
    INDEX IDX_SD_PRDT_CLSF_NM (PRDT_CLSF_NM)
) COMMENT='종목 상세';

CREATE TABLE IF NOT EXISTS STOCK_TAG_VALUE (
    ID          BIGINT       NOT NULL AUTO_INCREMENT,
    FIELD       VARCHAR(20)  NOT NULL COMMENT '분류 차원 (TagField 이름)',
    TAG_VALUE   VARCHAR(130) NOT NULL COMMENT 'KRX/KIS 분류 값 원문',
    LABEL       VARCHAR(130) NOT NULL COMMENT '화면 표시명 (기본=원문값)',
    CREATED_AT  DATETIME(6)  NOT NULL,
    UPDATED_AT  DATETIME(6)  NOT NULL,
    PRIMARY KEY (ID),
    UNIQUE KEY UK_STV_FIELD_VALUE (FIELD, TAG_VALUE),
    INDEX IDX_STV_FIELD (FIELD)
) COMMENT='종목 분류 값 마스터 (수집 시 자동 등록, 표시명 편집)';

CREATE TABLE IF NOT EXISTS STOCK_EVENT (
    ID          BIGINT       NOT NULL AUTO_INCREMENT,
    TICKER      VARCHAR(20)  NOT NULL COMMENT '종목코드',
    EVENT_TYPE  VARCHAR(20)  NOT NULL COMMENT '이벤트 유형 (StockEventType)',
    EVENT_DATE  DATE         NOT NULL COMMENT '이벤트 기준일 (KSD record_date)',
    SUMMARY     VARCHAR(200) COMMENT '표시용 요약',
    DETAIL      TEXT         COMMENT 'KSD 원본 응답 JSON',
    SOURCE      VARCHAR(20)  COMMENT '수집 출처 (예: KIS_KSD)',
    CREATED_AT  DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (ID),
    UNIQUE KEY UK_SE_TICKER_TYPE_DATE (TICKER, EVENT_TYPE, EVENT_DATE),
    INDEX IDX_SE_TICKER_DATE (TICKER, EVENT_DATE),
    INDEX IDX_SE_EVENT_DATE (EVENT_DATE)
) COMMENT='종목 권리 이벤트 (배당·증자·감자·합병/분할·액면, KIS 예탁원정보)';

CREATE TABLE IF NOT EXISTS STOCK_PRICE (
    TICKER      VARCHAR(20)  NOT NULL,
    EXCHANGE    TINYINT      NOT NULL COMMENT '거래소 코드(KOSPI/KOSDAQ/KONEX/NXT/INTEGRATED)',
    PRICE_TYPE  TINYINT      NOT NULL COMMENT '가격유형 코드(RAW/ADJUSTED)',
