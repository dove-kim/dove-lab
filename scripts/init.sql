-- 수동 수집 작업 (재조회 진행률/에러)
CREATE TABLE IF NOT EXISTS COLLECTION_TASK (
    ID            BIGINT       NOT NULL AUTO_INCREMENT,
    TYPE          VARCHAR(10)  NOT NULL COMMENT 'STOCK/PRICE/EVENT',
    SCOPE         VARCHAR(100) NOT NULL COMMENT '수집 범위 표시 문자열',
    EXCHANGE      VARCHAR(10)            COMMENT '대상 거래소 (PRICE만, STOCK/EVENT는 NULL)',
    FROM_DATE     DATE         NOT NULL COMMENT '수집 시작일 (재실행 파라미터)',
    TO_DATE       DATE         NOT NULL COMMENT '수집 종료일 (재실행 파라미터)',
    STATUS        VARCHAR(10)  NOT NULL COMMENT 'PENDING/RUNNING/DONE/FAILED',
    TOTAL         INT          NOT NULL DEFAULT 0,
    DONE          INT          NOT NULL DEFAULT 0,
    ADJUSTED_TOTAL INT         NOT NULL DEFAULT 0 COMMENT '수정주가 재조회 대상 종목 수 (0=없음)',
    ADJUSTED_DONE  INT         NOT NULL DEFAULT 0 COMMENT '수정주가 재조회 완료 종목 수',
    ERROR_CODE    VARCHAR(50),
    ERROR_DETAIL  VARCHAR(1000),
    REQUESTED_BY  BIGINT,
    CREATED_AT    DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    STARTED_AT    DATETIME(6),
    PROGRESS_AT   DATETIME(6) COMMENT '진행률 마지막 갱신 시각 (ETA 계산 기준)',
    FINISHED_AT   DATETIME(6),
    PRIMARY KEY (ID),
    INDEX IDX_CT_STATUS (STATUS),
    INDEX IDX_CT_CREATED_AT (CREATED_AT)
) COMMENT='수동 수집 작업';

