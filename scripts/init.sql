    CREATED_AT      DATETIME(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (TICKER, EFFECTIVE_DATE),
    INDEX IDX_SHARE_EFFECTIVE (EFFECTIVE_DATE)
) COMMENT='상장주식수 변경이력(as-of 조회)' ROW_FORMAT=COMPRESSED KEY_BLOCK_SIZE=8;
